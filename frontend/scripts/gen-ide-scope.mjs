/**
 * Generates src/styles/ide-scope.css from globals.css (PRACTICE_POLISH_PLAN.md §5.1).
 *
 * The site's dark colours live only on `:root[data-theme='dark']`, so they cannot be
 * applied to one subtree. The IDE needs exactly that (code in dark while the site is
 * light, or the reverse), so this copies every token the dark block overrides into
 * `.ide-dark`, and the same tokens' light values into `.ide-light`.
 *
 *   node scripts/gen-ide-scope.mjs      (run after changing theme tokens; scripts/polish.test.ts checks it)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(join(root, 'src/styles/globals.css'), 'utf8');

const block = (startRe) => {
  const m = startRe.exec(css);
  if (!m) throw new Error(`block not found: ${startRe}`);
  let depth = 0;
  for (let i = m.index + m[0].length - 1; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) return css.slice(m.index + m[0].length, i);
  }
  throw new Error('unclosed block');
};
const props = (body) => {
  const out = new Map();
  for (const m of body.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) out.set(m[1], m[2].trim());
  return out;
};

const light = props(block(/^:root\s*\{/m));
const dark = props(block(/^:root\[data-theme='dark'\]\s*\{/m));
const names = [...dark.keys()].filter((n) => light.has(n));
const decl = (map) => names.map((n) => `  ${n}: ${map.get(n)};`).join('\n');
// Tokens built from other tokens (e.g. --bg-surface: rgb(var(--rgb-bg-surface))) are computed where they
// are declared, so they are re-declared inside the scope to pick up its colours.
const derived = [...light.entries()].filter(([n, v]) => !names.includes(n) && /var\(--/.test(v));
const derivedDecl = derived.map(([n, v]) => `  ${n}: ${v};`).join('\n');

const out = `/* GENERATED by scripts/gen-ide-scope.mjs from globals.css. Do not edit by hand.
   The IDE's own theme scope: the whole IDE follows its editor theme, whatever the site theme is. */
.ide-scope.ide-dark {
  color-scheme: dark;
${decl(dark)}
${derivedDecl}
}
.ide-scope.ide-light {
  color-scheme: light;
${decl(light)}
${derivedDecl}
}
`;
writeFileSync(join(root, 'src/styles/ide-scope.css'), out);
console.log(`ide-scope.css: ${names.length} tokens + ${derived.length} derived`);
